#!/usr/bin/env python3
"""Generate platform adapters from the canonical SVGs; --check detects drift."""
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
outputs = {}
def emit(path, text):
    outputs[path] = text

def name(stem):
    return ''.join(part[0].upper() + part[1:] for part in stem.split('-')) + 'Icon'

def element(node, native=False):
    tag = node.tag.split('}')[-1]
    props = { {'fill-rule':'fillRule','clip-rule':'clipRule','viewBox':'viewBox'}.get(k,k):v for k,v in node.attrib.items() }
    children = [element(c, native) for c in node]
    if tag == 'svg':
        props = '{...'+json.dumps(props)+', width: size, height: size, '+('color, ' if native else 'color, "aria-hidden": props["aria-label"] || props["aria-labelledby"] ? undefined : true, ')+ '...props}'
    else:
        props = json.dumps(props)
    target = tag.capitalize() if native else json.dumps(tag)
    return 'createElement('+target+', '+props+(' ,'+', '.join(children) if children else '')+')'

icons = sorted((ROOT/'icons').glob('*.svg'))
for platform in ['react','react-native']:
    native = platform == 'react-native'
    exports = []
    for svg in icons:
        symbol = name(svg.stem)
        root = ET.parse(svg).getroot()
        imports = 'import { createElement, forwardRef } from "react";\n'
        if native: imports += 'import { Svg, Path, Circle, Rect, G } from "react-native-svg";\n'
        body = element(root, native).replace('...props}', '...props, ref}')
        emit(f'packages/iconscxl/dist/{platform}/{svg.stem}.js', imports + f'export const {symbol} = /*#__PURE__*/ forwardRef(function {symbol}({{size = 16, color = "currentColor", ...props}}, ref) {{\n  return {body};\n}});\n')
        types = 'import type { ForwardRefExoticComponent, RefAttributes, '+('ComponentRef' if native else 'SVGProps')+' } from "react";\n'
        if native:
            types += 'import type { Svg } from "react-native-svg";\nimport type { SvgProps } from "react-native-svg";\n'
        props = 'SvgProps' if native else 'SVGProps<SVGSVGElement>'
        ref = 'ComponentRef<typeof Svg>' if native else 'SVGSVGElement'
        emit(f'packages/iconscxl/dist/{platform}/{svg.stem}.d.ts', types + f'export declare const {symbol}: ForwardRefExoticComponent<Omit<{props}, "ref"> & {{ size?: number; color?: string }} & RefAttributes<{ref}>>;\n')
        exports.append(f'export {{ {symbol} }} from "./{svg.stem}.js";')
    for ext in ['js','d.ts']: emit(f'packages/iconscxl/dist/{platform}/index.{ext}', '\n'.join(exports)+'\n')
for file in ['LICENSE','NOTICE','THIRD_PARTY_LICENSES.md']:
    emit(f'packages/iconscxl/{file}', (ROOT/file).read_text())

exports = []
for svg in icons:
    symbol = name(svg.stem)
    emit(f'packages/iconscxl/dist/js/{svg.stem}.js', f'export const {symbol} = '+json.dumps(svg.read_text())+';\n')
    emit(f'packages/iconscxl/dist/js/{svg.stem}.d.ts', f'export declare const {symbol}: string;\n')
    exports.append(f'export {{ {symbol} }} from "./{svg.stem}.js";')
for ext in ['js','d.ts']:
    emit(f'packages/iconscxl/dist/js/index.{ext}', '\n'.join(exports)+'\n')


cases = []
for svg in icons:
    symbol = name(svg.stem)[:-4]
    symbol = symbol[0].lower()+symbol[1:]
    cases.append(f'    case `{symbol}` = "{svg.stem}"')
    base = f'Sources/IconsCXL/Resources/Icons.xcassets/{svg.stem}.imageset'
    emit(base+'/'+svg.name, svg.read_text())
    emit(base+'/Contents.json', json.dumps({'images':[{'filename':svg.name,'idiom':'universal'}], 'info':{'author':'xcode','version':1},'properties':{'preserves-vector-representation':True,'template-rendering-intent':'template'}},indent=2)+'\n')
emit('Sources/IconsCXL/Resources/Icons.xcassets/Contents.json', '{"info":{"author":"xcode","version":1}}\n')
for file in ['LICENSE','NOTICE','THIRD_PARTY_LICENSES.md']:
    emit('Sources/IconsCXL/Resources/'+file, (ROOT/file).read_text())
emit('Sources/IconsCXL/Icon.swift', '// Generated by scripts/generate.py.\nimport Foundation\n\npublic enum Icon: String, CaseIterable, Sendable, IconResource {\n'+'\n'.join(cases)+ '\n    public var resourceName: String { rawValue }\n}\n')
# Explicit style namespaces keep the existing default API stable.
catalog = json.loads((ROOT/'catalog.json').read_text())
emit('packages/iconscxl/dist/catalog.json', json.dumps(catalog, indent=2)+'\n')
for style in ['solid', 'stroke']:
    styled = sorted((ROOT/'icons/styles'/style).glob('*.svg'))
    for platform in ['js', 'react', 'react-native']:
        exports = []
        for svg in styled:
            # Reuse adapter rendering and declarations so accessibility and refs
            # behave identically in every style.
            symbol = name(svg.stem)
            base = f'packages/iconscxl/dist/{platform}/'
            if platform == 'js':
                js = f'export const {symbol} = '+json.dumps(svg.read_text())+';\n'
            else:
                native = platform == 'react-native'
                root = ET.parse(svg).getroot()
                imports = 'import { createElement, forwardRef } from "react";\n'
                if native: imports += 'import { Svg, Path, Circle, Rect, G } from "react-native-svg";\n'
                body = element(root, native).replace('...props}', '...props, ref}')
                js = imports + f'export const {symbol} = /*#__PURE__*/ forwardRef(function {symbol}({{size = 16, color = "currentColor", ...props}}, ref) {{\n  return {body};\n}});\n'
            emit(base+f'{style}/{svg.stem}.js', js)
            emit(base+f'{style}/{svg.stem}.d.ts', outputs[base+svg.stem+'.d.ts'])
            exports.append(f'export {{ {symbol} }} from "./{style}/{svg.stem}.js";')
        for ext in ['js', 'd.ts']:
            emit(f'packages/iconscxl/dist/{platform}/{style}.{ext}', '\n'.join(exports)+'\n')
    cases = []
    for svg in styled:
        symbol = name(svg.stem)[:-4]
        symbol = symbol[0].lower()+symbol[1:]
        cases.append(f'    case `{symbol}` = "{svg.stem}"')
        base = f'Sources/IconsCXL/Resources/Icons.xcassets/{style}--{svg.stem}.imageset'
        emit(base+'/'+svg.name, svg.read_text())
        emit(base+'/Contents.json', json.dumps({'images':[{'filename':svg.name,'idiom':'universal'}], 'info':{'author':'xcode','version':1},'properties':{'preserves-vector-representation':True,'template-rendering-intent':'template'}},indent=2)+'\n')
    enum = style.title()+'Icon'
    emit(f'Sources/IconsCXL/{enum}.swift', '// Generated by scripts/generate.py.\nimport Foundation\n\npublic enum '+enum+': String, CaseIterable, Sendable, IconResource {\n'+'\n'.join(cases)+f'\n    public var resourceName: String {{ "{style}--" + rawValue }}\n'+'}\n')
# Gallery is a generated offline artifact: no server, fetch or CDN required.
artwork = {}
for item in catalog:
    name_ = item['name']
    artwork[name_] = {}
    for style in item['styles']:
        source = ROOT/'icons'/((name_+'.svg') if style == 'duotone' else f'styles/{style}/{name_}.svg')
        artwork[name_][style] = source.read_text()
template = (ROOT/'scripts/gallery.html').read_text()
emit('index.html', template.replace('@@COUNT@@', str(len(icons))).replace('@@CATALOG@@', json.dumps(catalog)).replace('@@ARTWORK@@', json.dumps(artwork)))
# Keep the human-readable coverage specification in sync with the actual set.
from collections import Counter
counts = Counter(i['category'] for i in catalog)
coverage = '# Coverage catalog\n\n'+f'{len(icons)} names; {len(icons) + sum(len(i["styles"])-1 for i in catalog)} SVG drawings across the available styles.\n\n'
coverage += '| Category | Names |\n| --- | ---: |\n'+'\n'.join(f'| {c} | {n} |' for c,n in sorted(counts.items()))+'\n'
for category in sorted(counts):
    coverage += '\n## '+category+'\n\n'+', '.join('`'+i['name']+'`' for i in catalog if i['category']==category)+'\n'
emit('docs/CATALOG.md', coverage)
failed = []
for path, text in outputs.items():
    p = ROOT/path
    if '--check' in sys.argv:
        if not p.exists() or p.read_text() != text: failed.append(path)
    else:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
for directory in ['packages/iconscxl/dist','Sources/IconsCXL/Resources/Icons.xcassets']:
    for p in (ROOT/directory).rglob('*'):
        if p.is_file() and str(p.relative_to(ROOT)) not in outputs:
            if '--check' in sys.argv: failed.append(str(p.relative_to(ROOT)))
            else: p.unlink()
if failed:
    sys.exit('Generated files out of date: '+', '.join(failed))
print(f'{len(icons)} icons: generated files '+('verified' if '--check' in sys.argv else 'written'))
